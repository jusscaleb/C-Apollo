/*
Where the tokens used in the compiler are stored.
*/
#ifndef APOLLO_TOKEN_H
#define APOLLO_TOKEN_H

#include "defs.h"
#include <stdio.h>

typedef struct errorStack errorStack;


/*-------------TOKEN TYPES-------------*/
typedef enum {
  TOKEN_FXN, //----------------------------------------------------------> fxn
  TOKEN_EOF, //----------------------------------------------------------> \0
  TOKEN_RUN, //----------------------------------------------------------> run()
  TOKEN_VOID, //---------------------------------------------------------->
              //(void)
  TOKEN_IDENTIFIER, //---------------------------------------------------------->
                    //undefined tokens
  TOKEN_ARROW,  //----------------------------------------------------------> ->
  TOKEN_STRING, //---------------------------------------------------------->
                //"Apollo"
  TOKEN_LPARETH, //----------------------------------------------------------> (
  TOKEN_RPARETH, //----------------------------------------------------------> )
  TOKEN_LBRACE,  //----------------------------------------------------------> {
  TOKEN_RBRACE,  //----------------------------------------------------------> }
  TOKEN_SEMICOLON, //---------------------------------------------------------->
                   //;
  TOKEN_INT,  //----------------------------------------------------------> e.g:
              //45
  TOKEN_DOUB, //---------------------------------------------------------->
              //e.g: 45.00000
  TOKEN_FLOAT, //---------------------------------------------------------->
               //e.g.: 45.000000
  TOKEN_ADD,   //----------------------------------------------------------> +
  TOKEN_MUL,   //----------------------------------------------------------> *
  TOKEN_SUB,   //----------------------------------------------------------> -
  TOKEN_DIV,   //----------------------------------------------------------> /
  TOKEN_MOD,   //----------------------------------------------------------> %
  TOKEN_INC,   //----------------------------------------------------------> ++
  TOKEN_DEC,   //----------------------------------------------------------> --
  TOKEN_AEQ,   //----------------------------------------------------------> +=
  TOKEN_SEQ,   //----------------------------------------------------------> -=
  TOKEN_MEQ,   //----------------------------------------------------------> *=
  TOKEN_DEQ,   //----------------------------------------------------------> /=
  TOKEN_PEQ,   //----------------------------------------------------------> %=
  TOKEN_PRINTLN, //---------------------------------------------------------->
                 //println
  TOKEN_VAR, //----------------------------------------------------------> var
  TOKEN_ASSIGN, //----------------------------------------------------------> =
  TOKEN_BOOL,   // ---------------------------------------------------------->
                // true/false
  TOKEN_NULL,   // ---------------------------------------------------------->
                // null
  TOKEN_EQT,    //----------------------------------------------------------> ==
  TOKEN_NEQ,    //----------------------------------------------------------> !=
  TOKEN_GT,     //----------------------------------------------------------> >
  TOKEN_ST,     //----------------------------------------------------------> <
  TOKEN_GE,     //----------------------------------------------------------> >=
  TOKEN_SE,     //----------------------------------------------------------> <=
  TOKEN_AND,    //---------------------------------------------------------->
                //and/&&
  TOKEN_OR, //----------------------------------------------------------> or/||
  TOKEN_IF, //----------------------------------------------------------> if()
  TOKEN_ELIF, //---------------------------------------------------------->elif()
  TOKEN_ELSE,  //---------------------------------------------------------->
               //else{}
  TOKEN_WHILE, //---------------------------------------------------------->
               //while()
  TOKEN_FOR, //----------------------------------------------------------> for()

} TokenType;





/*-------------DEFINING THE TOKEN-------------*/
typedef struct {
  TokenType type;    // Token type
  const char *start; // RAM Address of Token
  int length;        //
  int line;
} Token;

/*Tells compiler that the variable exists in another file,
  Check lexer.c
*/
extern const char *TokenNames[];

// ACTS AS A POINTER THAT KEEPS TRACK OF POSITION IN SOURCE CODE
typedef struct {
  const char *current;
  int line;
  int column;
  errorStack *errors;
} Lexer;

// Called by parser.c
Token next_token(Lexer *lexer);

// Tracks the internal stream state of parser.
typedef struct {
  Lexer *lexer;   // takes lexer details (current character, current line)
  Token current;  // takes details of the current token
  Token previous; // takes details of the previous token
  errorStack *error;
} Parser;

#endif
